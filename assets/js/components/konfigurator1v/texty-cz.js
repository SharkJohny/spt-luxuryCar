export function prelozRetazecCz(text) {
  const s = String(text == null ? "" : text);
  return TEXTY.has(s) ? TEXTY.get(s) : prelozDynamicky(s);
}

export function prelozTextyCz(hodnota, cesta) {
  const path = cesta || "";
  if (typeof hodnota === "string") return prelozRetazecCz(hodnota);
  if (typeof hodnota === "function") return function () {
    const args = Array.prototype.slice.call(arguments);
    return FUNKCIE[path] ? FUNKCIE[path](hodnota, args) : prelozRetazecCz(hodnota.apply(this, args));
  };
  if (Array.isArray(hodnota)) return hodnota.map((v, i) => prelozTextyCz(v, path + "[" + i + "]"));
  if (!hodnota || typeof hodnota !== "object") return hodnota;
  const out = {};
  Object.keys(hodnota).forEach((k) => { const p = path ? path + "." + k : k; out[k] = prelozTextyCz(hodnota[k], p); });
  return out;
}
